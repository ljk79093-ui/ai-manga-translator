// ===================== 数字/日期格式化辅助 =====================
/**
 * 将日式日期格式（如 2024年12月1日）转为中文常见形式
 * @param {string} text
 * @returns {string}
 */
function normalizeDate(text) {
  // 日式：2023年12月1日 → 2023年12月1日（相同）但也可以处理 2023-12-01
  return text.replace(/(\d{4})[\/\\-](\d{1,2})[\/\\-](\d{1,2})/g, '$1年$2月$3日');
}

/**
 * 将全角数字转为半角数字
 * @param {string} text
 * @returns {string}
 */
function fullToHalfNumbers(text) {
  return text.replace(/[０-９]/g, s => String.fromCharCode(s.charCodeAt(0) - 0xFEE0));
}

// ===================== 标点与空白规范化 =====================
/**
 * 统一标点符号，中英文标点转为中文习惯
 * @param {string} text
 * @returns {string}
 */
function normalizePunctuation(text) {
  // 句号
  text = text.replace(/\./g, '。');
  // 逗号
  text = text.replace(/,/g, '，');
  // 省略号
  text = text.replace(/\.{3,}/g, '……');
  // 顿号
  text = text.replace(/、/g, '、');
  // 问号
  text = text.replace(/\?/g, '？');
  // 感叹号
  text = text.replace(/!/g, '！');
  // 破折号
  text = text.replace(/--/g, '——');
  // 多余空白
  text = text.replace(/\s+/g, ' ');
  // 去除首尾空格
  text = text.trim();
  return text;
}

// ===================== 用户自定义词典管理 =====================
let userDictionary = {};

/**
 * 从 storage 加载用户自定义词典，合并到内置词表中
 * 用户词典格式：{ "原文": "译文", ... }
 */
async function loadUserDictionary() {
  const result = await chrome.storage.sync.get('customDict');
  userDictionary = result.customDict || {};
}

/**
 * 合并多个映射表，后面的覆盖前面的
 * @param  {...Object} maps
 * @returns {Object}
 */
function mergeMaps(...maps) {
  return Object.assign({}, ...maps);
}

// ===================== 上下文规则引擎 =====================
/**
 * 根据原文语境微调译文（示例规则，可扩展）
 * @param {string} text - 翻译后的文本
 * @param {string} original - 原始 OCR 文本
 * @returns {string} 调整后的文本
 */
function applyContextRules(text, original) {
  if (!original) return text;
  // 如果原文包含「たい」且译文中有「想」，改为「要」更口语化
  if (original.includes('たい') && text.includes('想')) {
    text = text.replace('想', '要');
  }
  // 如果原文以「です」结尾，译文结尾可添加句号
  if (original.endsWith('です') && !text.endsWith('。')) {
    text += '。';
  }
  // 更多规则可在此添加
  return text;
}

// ===================== 主要后处理函数 =====================
/**
 * 对单个翻译文本进行后处理
 * @param {string} text - 翻译后的文本
 * @param {string} targetLang - 目标语言代码
 * @param {string} originalText - 原始文本（可选，用于上下文规则）
 * @returns {string} 处理后的文本
 */
function postProcessText(text, targetLang, originalText) {
  if (!text) return text;

  // 1. 数值格式化
  text = fullToHalfNumbers(text);
  text = normalizeDate(text);

  // 2. 用户词典优先级最高
  for (const [key, val] of Object.entries(userDictionary)) {
    const regex = new RegExp(key.replace(/[.*+?^${}()|[\]\\]/g, '\\$&'), 'g');
    text = text.replace(regex, val);
  }

  // 3. 内置词表替换（注意：先替换长词再替换短词是更好的策略，此处为简化直接遍历）
  let soundMap = {};
  let fixMap = TRANSLATION_FIX_MAP;
  if (targetLang === 'ja' || targetLang === 'JP') {
    soundMap = JP_SOUND_MAP;
  } else if (targetLang === 'ko' || targetLang === 'KR') {
    soundMap = KO_SOUND_MAP;
  } else if (targetLang === 'en' || targetLang === 'EN') {
    soundMap = EN_SOUND_MAP;
  } else {
    soundMap = mergeMaps(JP_SOUND_MAP, KO_SOUND_MAP, EN_SOUND_MAP);
  }

  // 合并所有词典（内置→用户→错译修正）
  const combinedMap = mergeMaps(soundMap, fixMap, userDictionary);

  // 对原文可能有日语拟声词时（仅当目标语言为中文）
  if (targetLang === 'zh' || targetLang === '中文' || targetLang === 'CN' || targetLang === 'ZH') {
    for (const [src, dest] of Object.entries(combinedMap)) {
      const regex = new RegExp(src.replace(/[.*+?^${}()|[\]\\]/g, '\\$&'), 'g');
      text = text.replace(regex, dest);
    }
  }

  // 4. 繁简转换 (仅当目标语言为中文)
  if (targetLang === 'zh' || targetLang === '中文' || targetLang === 'CN' || targetLang === 'ZH') {
    for (const [trad, simp] of Object.entries(T2S_MAP)) {
      const regex = new RegExp(trad, 'g');
      text = text.replace(regex, simp);
    }
  }

  // 5. 标点规范化
  text = normalizePunctuation(text);

  // 6. 上下文规则
  text = applyContextRules(text, originalText);

  return text;
}

/**
 * 批量后处理翻译结果
 * @param {Array<{text: string, originalText?: string}>} items - 翻译项数组
 * @param {string} targetLang - 目标语言
 * @returns {Array} 处理后的项
 */
function postProcessItems(items, targetLang) {
  if (!items || !items.length) return items;
  return items.map(item => ({
    ...item,
    text: postProcessText(item.text, targetLang, item.originalText || '')
  }));
}

